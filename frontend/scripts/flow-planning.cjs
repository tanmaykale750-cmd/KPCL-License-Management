const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('http://127.0.0.1:5173/overview');
  await page.evaluate(() => localStorage.clear());
  await page.goto('http://127.0.0.1:5173/planning?tab=optimise&licence=ANS-MECH');
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'scripts/screens/plan-opt.png' });
  await page.getByRole('button', { name: /Open in what-if/ }).click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'scripts/screens/plan-whatif-seeded.png', fullPage: true });
  await page.getByLabel('Scenario name').fill('Combined plan');
  await page.getByRole('button', { name: /Save as Rev B/ }).click();
  await page.waitForTimeout(400);
  await page.getByRole('tab', { name: 'Assistant' }).click().catch(() => page.getByText('Assistant', { exact: true }).click());
  await page.waitForTimeout(500);
  await page.getByRole('button', { name: /Will we run short of ANSYS/ }).first().click();
  await page.getByLabel('Ask a planning question').fill('What happens if Project Y moves 4 weeks later?');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'scripts/screens/plan-assistant.png' });
  console.log('URL', page.url());
  if (errors.length) console.log('ERRORS:\n' + errors.join('\n'));
  await browser.close();
})();
